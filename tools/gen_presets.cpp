// Generate the LV2 presets from src/presets.hpp:
//   dopplerit.lv2/presets.ttl  the port values of every preset
//   dopplerit.lv2/manifest.ttl the plugin and the preset list
//
//   make presets

#include "presets.hpp"

#include <cstdio>
#include <string>

using namespace dopplerit;

static const char* kUri = "https://github.com/pilali/dopplerit";

static std::string num(double v)
{
    char b[32];
    std::snprintf(b, sizeof(b), "%.4g", v);
    std::string s(b);
    if (s.find_first_of(".e") == std::string::npos) s += ".0";
    return s;
}

int main(int argc, char** argv)
{
    const std::string dir = argc > 1 ? argv[1] : "dopplerit.lv2";

    FILE* m = std::fopen((dir + "/manifest.ttl").c_str(), "w");
    FILE* p = std::fopen((dir + "/presets.ttl").c_str(), "w");
    if (m == nullptr || p == nullptr) { std::perror("gen_presets"); return 1; }

    const char* header =
        "# Generated by tools/gen_presets.cpp from src/presets.hpp, do not edit\n\n"
        "@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n"
        "@prefix pset: <http://lv2plug.in/ns/ext/presets#> .\n"
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n\n";
    std::fputs(header, m);
    std::fputs(header, p);

    std::fprintf(m, "<%s>\n    a lv2:Plugin ;\n    lv2:binary <dopplerit.so> ;\n"
                    "    rdfs:seeAlso <dopplerit.ttl> , <modgui.ttl> .\n", kUri);

    for (int i = 0; i < kNumPresets; ++i) {
        const Preset& pr = kPresets[i];
        std::fprintf(m, "\n<%s#preset-%s>\n    a pset:Preset ;\n    lv2:appliesTo <%s> ;\n"
                        "    rdfs:label \"%s\" ;\n    rdfs:seeAlso <presets.ttl> .\n",
                     kUri, pr.id, kUri, pr.name);

        const struct { const char* sym; double v; } ports[] = {
            { "mode", (double)pr.mode }, { "time", pr.time }, { "speed", pr.speedKmh },
            { "depth", pr.depth }, { "shape", pr.shape }, { "period", pr.period },
            { "feedback", pr.feedback }, { "tone", pr.tone }, { "mix", pr.mix },
        };
        std::fprintf(p, "<%s#preset-%s>\n    a pset:Preset ;\n    lv2:appliesTo <%s> ;\n"
                        "    rdfs:label \"%s\" ;\n    lv2:port",
                     kUri, pr.id, kUri, pr.name);
        const int n = (int)(sizeof(ports) / sizeof(ports[0]));
        for (int k = 0; k < n; ++k)
            std::fprintf(p, "%s [\n        lv2:symbol \"%s\" ;\n        pset:value %s\n    ]",
                         k == 0 ? "" : " ,", ports[k].sym, num(ports[k].v).c_str());
        std::fputs(" .\n\n", p);
    }
    std::fclose(m);
    std::fclose(p);
    std::printf("%d presets written to %s\n", kNumPresets, dir.c_str());
    return 0;
}
